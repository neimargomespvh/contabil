import { Type } from 'class-transformer';
import { IsInt, IsOptional, IsUUID, IsDateString, Min, Max } from 'class-validator';

export class FilterLancamentoDto {
  @IsUUID() empresaId: string;

  @IsOptional() @IsDateString() competencia?: string;

  @IsOptional() @Type(() => Number)
  @IsInt() @Min(1) page: number = 1;

  @IsOptional() @Type(() => Number)
  @IsInt() @Min(1) @Max(100) limit: number = 30;
}